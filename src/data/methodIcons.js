/** The image address for a method, or null when it has none. */
export function methodIconSrc(method) {
  const file = method?.icon || METHOD_ICONS[method?.id]
  if (!file) return null
  return /^(https?:)?\/\//.test(file) || file.startsWith('/') ? file : `/icons/methods/${file}`
}
